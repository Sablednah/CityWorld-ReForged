#!/usr/bin/env python3
"""Write CityWorld's Cobblemon city spawn entries from Cobblemon's own urban ones.

Cobblemon's `urban` preset wants concrete within four blocks of a natural floor, which a CityWorld street never has
(terracotta pavement, stone-slab sidewalks), so none of its 101 urban entries fire in a city. This script copies
every spawn entry carrying the `urban` preset — species, bucket, level, weight, multipliers, biome conditions — and
replaces the preset with a `markers` condition on `cityworld:city`, the marker `CobblemonBridge` puts on a position
on a city's surface. The result is Cobblemon's own idea of what lives in a town, at Cobblemon's own weights, on
CityWorld's streets.

    scripts/gen_cobblemon_city_spawns.py <Cobblemon jar or an extracted data dir>

Re-run it when Cobblemon updates; the output names the version it was read from. The `natural` preset is dropped
with `urban` (its base-block rule fails on a slab sidewalk or a concrete roof); any other preset is kept.
"""
import io
import json
import os
import re
import sys
import zipfile

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'main', 'resources', 'data', 'cityworld',
                   'spawn_pool_world', 'cityworld_city.json')
DROP = {'urban', 'natural'}


def read_entries(source):
    files = {}
    if os.path.isdir(source):
        folder = os.path.join(source, 'data', 'cobblemon', 'spawn_pool_world')
        for root, _dirs, names in sorted(os.walk(folder)):
            for name in sorted(names):
                if name.endswith('.json'):
                    with open(os.path.join(root, name), encoding='utf-8') as fh:
                        files[os.path.relpath(os.path.join(root, name), folder)] = json.load(fh)
        version = os.path.basename(os.path.abspath(source))
    else:
        with zipfile.ZipFile(source) as jar:
            for name in sorted(jar.namelist()):
                if name.startswith('data/cobblemon/spawn_pool_world/') and name.endswith('.json'):
                    with jar.open(name) as fh:
                        files[name[len('data/cobblemon/spawn_pool_world/'):]] = json.load(io.TextIOWrapper(fh, encoding='utf-8'))
        m = re.search(r'(\d+\.\d+\.\d+)', os.path.basename(source))
        version = m.group(1) if m else os.path.basename(source)
    return files, version


def convert(entry):
    # a pokemon entry or a herd (herdablePokemon) — every key is kept but the three this rewrites
    # herds reuse their species entry's id (meowth-1 is both), so the herd copies say so
    out = {'id': ('cityworld-herd-' if 'herdablePokemon' in entry else 'cityworld-') + entry['id']}
    for key, value in entry.items():
        if key not in ('id', 'presets', 'condition'):
            out[key] = value
    presets = [p for p in entry.get('presets', []) if p not in DROP]
    if presets:
        out['presets'] = presets
    condition = dict(entry.get('condition', {}))
    condition['markers'] = ['cityworld:city']
    out['condition'] = condition
    # a herd names itself by its raw id in /checkspawns (SpawnDetail.getName: displayName ?: id), so the owner's
    # list read "cityworld-herd-meowth-1"; the leader species' lang key makes it read "Meowth", and the command
    # then folds it in with the single-Pokémon entry of the same name
    if 'herdablePokemon' in entry and 'displayName' not in entry:
        members = entry['herdablePokemon']
        lead = next((m for m in members if m.get('isLeader')), members[0] if members else None)
        if lead and lead.get('pokemon'):
            out['displayName'] = 'cobblemon.species.%s.name' % lead['pokemon'].split()[0].lower()
    return out


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    files, version = read_entries(argv[1])
    spawns = []
    for name, data in files.items():
        for entry in data.get('spawns', []):
            if 'urban' in entry.get('presets', []):
                spawns.append(convert(entry))
    doc = {
        '_comment': 'GENERATED by scripts/gen_cobblemon_city_spawns.py from Cobblemon %s: its urban spawn entries, '
                    'keyed on the cityworld:city marker instead of nearby concrete. Edit the script, not this file.' % version,
        'enabled': True,
        'neededInstalledMods': ['cobblemon'],
        'neededUninstalledMods': [],
        'spawns': spawns,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        json.dump(doc, fh, indent=2)
        fh.write('\n')
    species = sorted({s['pokemon'].split(' ')[0] for s in spawns if 'pokemon' in s})
    herds = sum(1 for s in spawns if 'herdablePokemon' in s)
    print('%d entries (%d herds), %d species, from Cobblemon %s -> %s' % (len(spawns), herds, len(species), version,
                                                                      os.path.relpath(OUT)))
    print(', '.join(species))


if __name__ == '__main__':
    main(sys.argv)
